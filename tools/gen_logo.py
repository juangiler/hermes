#!/usr/bin/env python3
"""Generate all Hermes logo assets from helmet.pixels; --check never writes.

Each source row is the left half of a symmetric 32px sprite. Dots are
transparent; O outline, W silver highlight, S silver shadow, Y gold highlight,
G gold. Edit that single grid, then run this script.
"""
import argparse
import json
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parent.parent
PALETTE = {".": (0, 0, 0, 0), "O": (27, 37, 59, 255),
           "W": (240, 247, 255, 255), "S": (151, 174, 199, 255),
           "Y": (255, 211, 110, 255), "G": (207, 139, 46, 255)}


def sprite():
    rows = (ROOT / "assets/branding/helmet.pixels").read_text().splitlines()
    if len(rows) != 32 or any(len(row) != 16 for row in rows):
        raise ValueError("helmet.pixels must contain 32 rows of 16 pixels")
    if any(char not in PALETTE for row in rows for char in row):
        raise ValueError("unknown palette symbol")
    return [row + row[::-1] for row in rows]


def svg(rows):
    pixels = []
    for y, row in enumerate(rows):
        for x, char in enumerate(row):
            if char != ".":
                color = "#{:02x}{:02x}{:02x}".format(*PALETTE[char][:3])
                pixels.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{color}"/>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" '
            'viewBox="0 0 32 32" shape-rendering="crispEdges">' + "".join(pixels) + "</svg>\n")


def chunk(kind, data):
    return (struct.pack(">I", len(data)) + kind + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff))


def png(rows, size):
    raw = bytearray()
    for y in range(size):
        raw.append(0)
        for x in range(size):
            raw.extend(PALETTE[rows[y * 32 // size][x * 32 // size]])
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))


def outputs():
    rows = sprite()
    artwork = svg(rows)
    # C string literals are split by pixel so compilers need no oversized line.
    svg_parts = artwork.rstrip().replace("><", ">\n<").splitlines()
    literal = "\n".join("  " + json.dumps(part) for part in svg_parts)
    header = ("/* Generated by tools/gen_logo.py; edit assets/branding/helmet.pixels. */\n"
              "#ifndef HERMES_LOGO_DATA_H\n#define HERMES_LOGO_DATA_H\n"
              "static const char *g_logo_svg =\n" + literal + ";\n"
              "static const char *g_logo_small_svg =\n" + literal + ";\n#endif\n")
    result = {ROOT / "assets/branding/hermes.svg": artwork.encode(),
              ROOT / "src/logo_data.h": header.encode()}
    for size in (16, 24, 32, 48, 64, 128, 256):
        result[ROOT / f"assets/branding/hermes-{size}.png"] = png(rows, size)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, data in outputs().items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        parser.exit(1, "Regenerate logo assets: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
